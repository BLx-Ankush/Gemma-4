def _trim_text(value: Optional[str], max_chars: int) -> str:
    if not value:
        return ""
    text = str(value).strip()
    if len(text) <= max_chars:
        return text
    return text[: max_chars - 3].rstrip() + "..."


def build_veda_prompt(language: str = "English", drug_context: str = "") -> str:
    drug_section = ""
    if drug_context:
        drug_section = (
            "\nRelevant drug information (incorporate naturally into your response):\n"
            + str(drug_context).strip()
        )

    return VEDA_SYSTEM_PROMPT.format(
        language=(language or "English"),
        drug_context=drug_section,
    )


def build_mirror_prompt(query: str, image_context: str, response: str) -> str:
    return MIRROR_SYSTEM_PROMPT.format(
        query=_trim_text(query, 400),
        image_context=_trim_text(image_context or "No image provided", 200),
        response=_trim_text(response, 1200),
    )


def apply_mirror_verdict(response: str, verdict: str, language_code: str = "en") -> str:
    lang = (language_code or "en").lower()[:2]
    normalized = (verdict or "warn").strip().lower()

    if normalized == "block":
        return SAFE_FALLBACKS.get(lang, SAFE_FALLBACK_EN)

    if normalized == "warn":
        caveat = WARN_CAVEATS.get(lang, WARN_CAVEAT_EN)
        return (response or "").strip() + caveat

    return response
